def lookup_city_coordinates(city: str, state: str) -> Optional[Tuple[float, float]]:
    """Lookup coordinates for any city and state in the 50-state database."""
    c = city.lower().strip()
    s = state.lower().strip()
    if (c, s) in CITY_COORDINATES:
        return CITY_COORDINATES[(c, s)]
    for (k_city, k_state), coords in CITY_COORDINATES.items():
        if k_state == s and (k_city in c or c in k_city):
            return coords
    return None
